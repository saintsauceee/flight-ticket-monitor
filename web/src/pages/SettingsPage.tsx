import { CircleCheck, FlaskConical } from 'lucide-react';
import type { ReactNode } from 'react';
import { CURRENCIES } from '@shared/types';
import { BagPrefsControl } from '@/components/Bags';
import { useMeta } from '@/components/Layout';
import { Card, cx, ErrorNote, Segmented, Select, Skeleton } from '@/components/ui';
import { plural } from '@/lib/format';
import { setPrefs, usePrefs, type ThemePref } from '@/lib/prefs';
import { useTitle } from '@/lib/useTitle';

function Code({ children }: { children: ReactNode }) {
  return <code className="code-face rounded bg-surface-2 px-1.5 py-0.5 text-[12px] text-ink-2">{children}</code>;
}

function Setting({ title, hint, children }: { title: string; hint: string; children: ReactNode }) {
  return (
    <div className="flex flex-wrap items-center justify-between gap-x-6 gap-y-2.5 px-4 py-3.5">
      {/* The text gives way and wraps; the control drops below only when there is no room for both. */}
      <div className="min-w-0 flex-1 basis-60">
        <div className="font-medium">{title}</div>
        <div className="text-[13px] text-ink-3">{hint}</div>
      </div>
      {children}
    </div>
  );
}

export function SettingsPage() {
  useTitle('Settings');
  const prefs = usePrefs();
  const { data: meta, isPending, error } = useMeta();
  const usage = meta?.usage;
  const share = usage?.budget ? Math.min(1, usage.used / usage.budget) : 0;
  const overBudget = usage?.budget != null && meta != null && meta.projectedMonthlySearches > usage.budget;

  return (
    <div className="mx-auto max-w-3xl space-y-8">
      <h1 className="text-xl font-semibold tracking-tight">Settings</h1>

      <section>
        <h2 className="mb-3 text-[15px] font-semibold tracking-tight">Data source</h2>
        {error ? (
          <ErrorNote message={error.message} />
        ) : isPending ? (
          <Skeleton className="h-40" />
        ) : (
          <Card>
            <div className="flex items-start gap-3 px-4 py-4">
              <span className={cx('mt-0.5 flex size-8 shrink-0 items-center justify-center rounded-full', meta.provider.demo ? 'bg-warn-soft text-warn-ink' : 'bg-good-soft text-good-ink')}>
                {meta.provider.demo ? <FlaskConical className="size-4" aria-hidden /> : <CircleCheck className="size-4" aria-hidden />}
              </span>
              <div className="min-w-0">
                <div className="font-medium">{meta.provider.label}</div>
                <p className="mt-0.5 text-[13px] text-ink-3">
                  {meta.provider.demo
                    ? 'Fares, schedules, bag fees and price history are generated by a simulator. They behave like real fares but are not real, so do not book against them.'
                    : 'Live fares from Google Flights. Fare rules and exact bag fees are loaded per flight when you ask for them.'}
                </p>
              </div>
            </div>

            {usage?.budget != null && (
              <div className="border-t border-line px-4 py-4">
                <div className="flex items-baseline justify-between gap-3 text-[13px]">
                  <span className="font-medium">Searches this month</span>
                  <span className="tnum text-ink-2">
                    {usage.used} of {usage.budget}
                  </span>
                </div>
                {/* Meter: the track is a lighter step of the fill's own hue. */}
                <div className="mt-2 h-2 overflow-hidden rounded-full bg-accent-soft" role="meter" aria-valuemin={0} aria-valuemax={usage.budget} aria-valuenow={usage.used} aria-label="Searches used this month">
                  <div className={cx('h-full rounded-full', share >= 0.9 ? 'bg-bad' : 'bg-accent')} style={{ width: `${share * 100}%` }} />
                </div>
                <p className={cx('mt-2 text-[13px]', overBudget ? 'font-medium text-warn-ink' : 'text-ink-3')}>
                  Your tracked trips need about {plural(meta.projectedMonthlySearches, 'search', 'searches')} a month at their current check intervals
                  {overBudget ? ', which is more than the budget. Lengthen some intervals or pause trips, or checks will stop when the budget runs out.' : '.'}
                </p>
              </div>
            )}

            {meta.provider.demo && (
              <div className="border-t border-line px-4 py-4 text-[13px]">
                <h3 className="font-medium">Connect live fares</h3>
                <ol className="mt-2 list-decimal space-y-1.5 pl-5 text-ink-2">
                  <li>
                    Create a key at{' '}
                    <a href="https://serpapi.com/google-flights-api" target="_blank" rel="noreferrer" className="font-medium text-accent-strong hover:underline">
                      serpapi.com
                    </a>{' '}
                    (its Google Flights API; the free plan covers a few hundred searches a month).
                  </li>
                  <li>
                    Put it in a <Code>.env</Code> file at the project root: <Code>SERPAPI_KEY=your-key</Code>
                  </li>
                  <li>Restart the server. This page then shows the live source and your monthly usage.</li>
                </ol>
                <p className="mt-2.5 text-ink-3">
                  Each search or scheduled check uses one search, so on a small plan track a handful of trips and check them daily. Trips tracked in demo mode keep their simulated
                  history; delete them before switching.
                </p>
              </div>
            )}
          </Card>
        )}
      </section>

      <section>
        <h2 className="mb-3 text-[15px] font-semibold tracking-tight">Preferences</h2>
        <Card className="divide-y divide-line">
          <Setting
            title="Bags per traveller"
            hint="Optional. Totals and airline comparisons add the fees for the bags you pick. Leave both at 0 to compare fares on their own."
          >
            <BagPrefsControl prefs={prefs.bags} label={false} />
          </Setting>
          <Setting title="Currency" hint="Used for new searches. Tracked trips keep the currency they were created with.">
            <Select label="Currency" variant="outline" value={prefs.currency} onChange={(currency) => setPrefs({ currency })}>
              {CURRENCIES.map((c) => (
                <option key={c} value={c}>
                  {c}
                </option>
              ))}
            </Select>
          </Setting>
          <Setting title="Theme" hint="Follow the system setting or pick one.">
            <Segmented<ThemePref>
              label="Theme"
              value={prefs.theme}
              onChange={(theme) => setPrefs({ theme })}
              options={[
                { value: 'system', label: 'System' },
                { value: 'light', label: 'Light' },
                { value: 'dark', label: 'Dark' },
              ]}
            />
          </Setting>
        </Card>
        <p className="mt-2 text-xs text-ink-3">Preferences are stored in this browser.</p>
      </section>
    </div>
  );
}
